@app.post("/api/v1/verdict", response_model=VerdictResponse, tags=["Simulation"], dependencies=[Depends(require_api_key)])
def verdict(request: VerdictRequest):
    return evaluate(request)

class Scenario(BaseModel):
    name: str = Field(min_length=1, max_length=80)
    multiplier: float = Field(gt=0, le=10)

class CompareRequest(BaseModel):
    engine: Literal["rules", "simpy"] = "rules"
    spec: ServerSpec
    load: Load
    scenarios: list[Scenario] = Field(default_factory=lambda: [Scenario(name="Baseline", multiplier=1), Scenario(name="2× traffic", multiplier=2), Scenario(name="3× traffic", multiplier=3)], min_length=1, max_length=5)

@app.post("/api/v1/scenarios/compare", tags=["Simulation"], dependencies=[Depends(require_api_key)])
def compare_scenarios(body: CompareRequest):
    runs = []
    for scenario in body.scenarios:
        load = body.load.model_copy(update={
            "rps": body.load.rps * scenario.multiplier,
            "concurrent_connections": round(body.load.concurrent_connections * scenario.multiplier),
        })
        response = evaluate(VerdictRequest(engine=body.engine, spec=body.spec, load=load))
        runs.append({"name": scenario.name, "multiplier": scenario.multiplier, "load": load.model_dump(), "result": response.model_dump()})
    return {"engine": body.engine, "scenarios": runs, "model_note": "Capacity predictions are not production measurements."}

class TopologyNode(BaseModel):
    id: str = Field(min_length=1, max_length=50)
    name: str = Field(min_length=1, max_length=80)
    online: bool = True
    weight: float = Field(default=1, ge=0, le=100)

class TopologyRequest(BaseModel):
    spec: ServerSpec
    load: Load
    nodes: list[TopologyNode] = Field(min_length=1, max_length=8)
    engine: Literal["rules", "simpy"] = "rules"

@app.post("/api/v1/topology/evaluate", tags=["Simulation"], dependencies=[Depends(require_api_key)])
def evaluate_topology(body: TopologyRequest):
    active = [node for node in body.nodes if node.online and node.weight > 0]
    if not active:
        return {"verdict": "no_capacity", "nodes": [{"id": node.id, "name": node.name, "online": node.online, "traffic_share": 0, "result": None} for node in body.nodes], "warning": "No available nodes"}
    total_weight = sum(node.weight for node in active)
    evaluated = []
    severity = {"will_survive": 0, "at_risk": 1, "will_crash": 2}
    max_severity = 0
    for node in body.nodes:
        if not node.online or node.weight == 0:
            evaluated.append({"id": node.id, "name": node.name, "online": False, "traffic_share": 0, "result": None})
            continue
        share = node.weight / total_weight
        assigned_load = body.load.model_copy(update={"rps": body.load.rps * share, "concurrent_connections": round(body.load.concurrent_connections * share)})
        output = evaluate(VerdictRequest(engine=body.engine, spec=body.spec, load=assigned_load))
        max_severity = max(max_severity, severity[output.verdict])
        evaluated.append({"id": node.id, "name": node.name, "online": True, "traffic_share": round(share, 4), "result": output.model_dump()})
    verdict = ["will_survive", "at_risk", "will_crash"][max_severity]
    return {"verdict": verdict, "nodes": evaluated, "warning": "Simplified independent-node traffic distribution, not a calibrated load-balancer queueing model."}

class SimulationRequest(VerdictRequest):
    label: str = Field(default="Untitled run", min_length=1, max_length=100)

@app.post("/api/v1/simulations", tags=["Simulation"], dependencies=[Depends(require_api_key)])
def create_simulation(body: SimulationRequest):
    output = evaluate(body)
    return {"id": str(uuid.uuid4()), "created_at": datetime.now(timezone.utc).isoformat(), "label": body.label, "input": body.model_dump(), "result": output.model_dump(), "saved": False, "message": "Result computed. The browser can save it locally; shared cloud history requires database setup."}

def verify_data_key(x_data_key: str | None = Header(default=None)):
    expected = os.getenv("DATA_API_KEY")
    if not expected or x_data_key != expected:
        raise HTTPException(403, "Private data API is not enabled or credentials are missing.")

def database():
    if not os.getenv("DATABASE_URL"):
        raise HTTPException(503, "Database not configured. Connect Neon and set DATABASE_URL.")
    import psycopg
    return psycopg.connect(os.environ["DATABASE_URL"], connect_timeout=5)

@app.post("/api/v1/private/runs", tags=["Private history"], dependencies=[Depends(verify_data_key)])
def persist_run(body: SimulationRequest):
    computed = create_simulation(body)
    with database() as conn:
        with conn.cursor() as cur:
            cur.execute("""CREATE TABLE IF NOT EXISTS simulation_runs (
                id uuid PRIMARY KEY,
                created_at timestamptz NOT NULL DEFAULT now(),
                label text NOT NULL,
                engine text NOT NULL,
                request_json jsonb NOT NULL,
                result_json jsonb NOT NULL
            )""")
            cur.execute("INSERT INTO simulation_runs (id, label, engine, request_json, result_json) VALUES (%s,%s,%s,%s::jsonb,%s::jsonb)",
                (computed["id"], body.label, body.engine, json.dumps(body.model_dump()), json.dumps(computed["result"])))
    return {**computed, "saved": True, "message": "Saved to PostgreSQL"}

@app.get("/api/v1/private/runs", tags=["Private history"], dependencies=[Depends(verify_data_key)])
def persisted_runs(limit: int = 20):
    with database() as conn:
        with conn.cursor() as cur:
            cur.execute("""CREATE TABLE IF NOT EXISTS simulation_runs (
                id uuid PRIMARY KEY,
                created_at timestamptz NOT NULL DEFAULT now(),
                label text NOT NULL,
                engine text NOT NULL,
                request_json jsonb NOT NULL,
                result_json jsonb NOT NULL
            )""")
            cur.execute("SELECT id::text, created_at, label, engine, request_json, result_json FROM simulation_runs ORDER BY created_at DESC LIMIT %s", (min(max(limit, 1), 100),))
            rows = cur.fetchall()
    return {"runs": [{"id": r[0], "created_at": r[1].isoformat(), "label": r[2], "engine": r[3], "input": r[4], "result": r[5]} for r in rows]}

@app.get("/api/v1/quality", tags=["System"])
def quality_summary():
    """Read live CI conclusion from GitHub, never fabricate coverage metrics."""
    data = {"source": "GitHub Actions", "repository": "adryanra97/server_agent", "status": "unavailable", "conclusion": None, "url": "https://github.com/adryanra97/server_agent/actions", "run_id": None, "coverage": None, "coverage_status": "not-reported"}
    try:
        req = Request("https://api.github.com/repos/adryanra97/server_agent/actions/workflows/quality.yml/runs?per_page=1", headers={"Accept": "application/vnd.github+json", "User-Agent": "ServerAgent"})
        with urlopen(req, timeout=3) as response:
            raw = json.load(response)
        if raw.get("workflow_runs"):
            run = raw["workflow_runs"][0]
            data.update(status=run.get("status"), conclusion=run.get("conclusion"), run_id=run.get("id"), url=run.get("html_url"))
        else:
            data["status"] = "not-run"
    except (URLError, OSError, ValueError, KeyError):
        pass
    return data
