def evaluate(request: VerdictRequest) -> VerdictResponse:
    engine = ENGINES.get(request.engine)
    if engine is None:
        raise HTTPException(422, f"Unknown engine: {request.engine}. Available: {', '.join(ENGINES)}")
    # SimPy's RAM Container cannot serve a request larger than its capacity.
    if request.engine == "simpy" and request.load.avg_mem_mb_per_req > request.spec.ram.total_mb:
        raise HTTPException(422, "Memory requested per transaction exceeds total RAM; reduce memory usage or increase RAM.")
    if request.engine == "simpy" and request.load.avg_mem_mb_per_req == 0 and request.load.rps > 0:
        # SimPy Container.get(0) is invalid. This case is still evaluable
        # deterministically, and the actual engine provenance must be visible.
        raise HTTPException(422, "SimPy currently requires nonzero memory per transaction; select Rules or a positive memory estimate.")
    result = engine.evaluate(EvaluationInput(spec=request.spec, load=request.load))
    return VerdictResponse(**result.model_dump(), engine=engine.name)

